import { _electron as electron } from 'playwright';
import { createRequire } from 'node:module';
import { createServer } from 'node:http';
import { once } from 'node:events';
import * as fs from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';

async function main() {
  const calls: string[] = [];
  const server = createServer(async (request, response) => {
    let raw = ''; for await (const part of request) raw += part;
    const body = JSON.parse(raw); calls.push(String(body.messages[1].content));
    const content = JSON.stringify({ characters: [{ name: '虚构人物', personality: '乐观' }], world: [{ title: '虚构城', type: '地点', content: '港口城市', keywords: '虚构城,港口' }] });
    response.writeHead(200, { 'Content-Type': 'text/event-stream' });
    response.end(`data: ${JSON.stringify({ choices: [{ index: 0, delta: { content }, finish_reason: 'stop' }] })}\n\ndata: [DONE]\n\n`);
  });
  server.listen(0, '127.0.0.1'); await once(server, 'listening');
  const fixture = await fs.mkdtemp(path.resolve('.artifacts/setting-book-'));
  const folder = path.join(fixture, '虚构小说'); await fs.mkdir(folder);
  const chapter = path.join(folder, '第一章.txt');
  const source = '开头标记。' + '虚构人物走过虚构城。'.repeat(1700) + '结尾标记。';
  await fs.writeFile(chapter, source, 'utf8');
  const args = process.argv.slice(2);
  assert.ok(args.length === 0 || (args.length === 2 && args[0] === '--exe' && path.isAbsolute(args[1]!)));
  const app = await electron.launch({ executablePath: args.length ? args[1]! : createRequire(import.meta.url)('electron'), args: args.length ? [] : [path.resolve('out/main/index.js')], env: { ...process.env, NOVEL_WRITER_TEST_DATA: path.join(fixture, 'data') } });
  try {
    if (args.length) { const info = await app.evaluate(({app}) => ({ packaged: app.isPackaged, version: app.getVersion() })); assert.equal(info.packaged, true); assert.equal(info.version, JSON.parse(await fs.readFile('package.json', 'utf8')).version); }
    const page = await app.firstWindow(); page.setDefaultTimeout(30000);
    page.on('dialog', dialog => void dialog.accept());
    await app.evaluate(({dialog}, selected) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [selected] }); }, folder);
    await page.getByRole('button', { name: '＋ 打开小说文件夹' }).click();
    await page.getByText('已打开「虚构小说」', { exact: false }).waitFor();
    const id = (await page.evaluate(() => window.writer.listProjects()))[0]!.id;
    await page.getByRole('button', { name: '模型设置', exact: true }).click();
    await page.getByLabel('连接名称', { exact: true }).fill('本机模拟模型');
    await page.getByLabel('API 基础地址', { exact: true }).fill(`http://127.0.0.1:${(server.address() as {port:number}).port}/v1`);
    await page.getByLabel('模型名称', { exact: true }).fill('mock-book');
    await page.getByRole('button', { name: '保存模型连接', exact: true }).click();
    await page.getByText('模型连接已保存', { exact: true }).waitFor();
    await page.getByRole('button', { name: '角色库', exact: true }).click();
    await page.getByTestId('setting-extract-open').click();
    await page.getByTestId('setting-book-prepare').click();
    await page.getByTestId('setting-book-preview').getByText(/已读取 1 章/u).waitFor();
    assert.equal(calls.length, 0, '读取预览不得调用模型');
    await page.getByTestId('setting-book-model').click();
    await page.getByLabel('选择 虚构人物').waitFor();
    assert.ok(calls.length > 1, '长篇应分段调用');
    const sent = calls.join(''); assert.ok(sent.includes(source), '正文不能截断');
    assert.equal((await page.evaluate(id => window.writer.readCharacters(id), id)).value.cards.length, 0);
    await page.getByText('查看并修改候选内容').first().click();
    await page.getByLabel('虚构人物 性格').fill('经作者核对的性格');
    await page.getByTestId('setting-confirm').click();
    await page.getByText(/已写入人物卡 1 张/u).waitFor();
    assert.equal((await page.evaluate(id => window.writer.readCharacters(id), id)).value.cards[0]!.personality, '经作者核对的性格');
    assert.equal(await fs.readFile(chapter, 'utf8'), source);
    await page.getByTestId('setting-open-world').click();
    const browser = page.getByTestId('world-card-browser'); await browser.waitFor();
    await browser.getByRole('heading', { name: '虚构城' }).waitFor();
    await browser.getByText('类型：地点', { exact: false }).waitFor();
    await browser.getByText('港口城市', { exact: false }).waitFor();
    assert.match(await browser.innerText(), /虚构城、港口/u);
    await browser.getByLabel('搜索设定卡').fill('找不到的地点');
    await browser.getByText('没有找到匹配的设定卡。').waitFor();
    await browser.getByLabel('搜索设定卡').fill('港口');
    await browser.getByRole('heading', { name: '虚构城' }).waitFor();
    await page.setViewportSize({ width: 1000, height: 720 });
    const overflow = await page.getByRole('dialog', { name: '世界书' }).evaluate(element => element.scrollWidth > element.clientWidth);
    assert.equal(overflow, false, '设定卡片窗口不应产生横向溢出');
    await page.getByRole('dialog', { name: '世界书' }).screenshot({ path: path.join(fixture, 'world-cards.png') });
    const other = await page.evaluate(async parent => window.writer.createProject(parent, '虚构另一本', true), fixture);
    await assert.rejects(page.evaluate(async ({ id, name }) => window.writer.readWorldBook(id, name), { id: other.project.id, name: (await browser.locator('h3').innerText()) }));
    await page.getByRole('dialog', { name: '世界书' }).locator('footer').getByRole('button', { name: '关闭' }).click();
    await page.getByRole('button', { name: '写作空间', exact: true }).click();
    const peoplePanel = page.getByRole('region', { name: '本书人物卡' });
    await peoplePanel.getByText('虚构人物', { exact: true }).waitFor();
    await peoplePanel.getByText('虚构人物', { exact: true }).click();
    await peoplePanel.getByText('经作者核对的性格').waitFor();
    await page.getByRole('button', { name: '世界观', exact: true }).click();
    const worldPanel = page.getByRole('region', { name: '本书世界设定卡' });
    await worldPanel.getByText('虚构城', { exact: true }).waitFor();
    await worldPanel.getByText('虚构城', { exact: true }).click();
    await worldPanel.getByText('港口城市', { exact: false }).waitFor();
    await page.locator('.inspector').screenshot({ path: path.join(fixture, 'inspector-cards.png') });
    const worldName = (await page.evaluate(id => window.writer.listWorldBooks(id), id))[0]!.name;
    const worldFile = path.join(folder, '小说资料', '世界书', `${worldName}.json`);
    const worldBefore = await fs.readFile(worldFile);
    await worldPanel.getByRole('button', { name: '编辑设定卡', exact: true }).click();
    let edit = page.getByRole('dialog', { name: '编辑世界设定卡' });
    await edit.getByLabel('设定卡内容').fill('港口城市，作者修订后。');
    assert.equal(await edit.locator('.world-card-editor').evaluate(element => element.scrollWidth > element.clientWidth), false);
    assert.equal(await edit.getByRole('button', { name: '保存设定卡' }).evaluate(element => { const button = element.getBoundingClientRect(); const screen = document.documentElement.getBoundingClientRect(); return button.top >= screen.top && button.bottom <= screen.bottom; }), true, '保存按钮应在视口内可见');
    await edit.screenshot({ path: path.join(fixture, 'world-card-editor.png') });
    await edit.getByRole('button', { name: '保存设定卡' }).click();
    await edit.waitFor({ state: 'detached' });
    const refreshedWorldPanel = page.getByRole('region', { name: '本书世界设定卡' });
    await refreshedWorldPanel.locator('details').filter({ hasText: '虚构城' }).locator('summary').evaluate((summary: HTMLElement) => { if (!(summary.parentElement as HTMLDetailsElement).open) summary.click(); });
    await refreshedWorldPanel.getByText('港口城市，作者修订后。', { exact: false }).waitFor();
    const backups = await fs.readdir(path.join(folder, '小说资料', '世界书修改备份'));
    assert.equal(backups.length, 1);
    assert.deepEqual(await fs.readFile(path.join(folder, '小说资料', '世界书修改备份', backups[0]!)), worldBefore);
    await refreshedWorldPanel.getByRole('button', { name: '编辑设定卡', exact: true }).click();
    edit = page.getByRole('dialog', { name: '编辑世界设定卡' });
    await edit.getByLabel('设定卡内容').fill('本机尚未保存的设定修改');
    await page.locator('button.save-exit').evaluate((button: HTMLElement) => button.click());
    assert.equal(await edit.getByLabel('设定卡内容').inputValue(), '本机尚未保存的设定修改', '保存退出不得丢弃卡片草稿');
    const external = (await fs.readFile(worldFile, 'utf8')) + '\n';
    await fs.writeFile(worldFile, external);
    await edit.getByRole('button', { name: '保存设定卡' }).click();
    await edit.getByRole('alert').getByText(/外部变化/u).waitFor();
    assert.equal(await edit.getByLabel('设定卡内容').inputValue(), '本机尚未保存的设定修改');
    assert.equal(await fs.readFile(worldFile, 'utf8'), external);
    await edit.getByRole('button', { name: '取消' }).click();
    await edit.waitFor({ state: 'detached' });
    await refreshedWorldPanel.getByRole('button', { name: '刷新', exact: true }).click();
    const updatedHash = createHash('sha256').update(external).digest('hex');
    await refreshedWorldPanel.locator(`details[data-book-hash="${updatedHash}"]`).waitFor();
    await page.waitForFunction(() => document.querySelector('[aria-label="本书世界设定卡"]')?.getAttribute('aria-busy') === 'false');
    const beforeDelete = JSON.parse(await fs.readFile(worldFile, 'utf8'));
    const deletionCard = refreshedWorldPanel.locator(`details[data-book-hash="${updatedHash}"]`).filter({ hasText: '虚构城' });
    if (await deletionCard.getAttribute('open') === null) await deletionCard.locator('summary').click();
    await refreshedWorldPanel.getByRole('button', { name: '删除设定卡', exact: true }).click();
    await refreshedWorldPanel.getByText('设定卡已删除并备份，可从回收站恢复。').waitFor();
    await refreshedWorldPanel.getByText('还没有世界设定卡片，可从下方入口创建或整理。').waitFor();
    assert.equal(Object.keys(JSON.parse(await fs.readFile(worldFile, 'utf8')).entries).length, 0);
    await refreshedWorldPanel.getByRole('button', { name: '设定卡回收站…' }).click();
    await refreshedWorldPanel.getByRole('button', { name: '恢复设定卡', exact: true }).click();
    await refreshedWorldPanel.getByText('已恢复「虚构城」，备份保留。').waitFor();
    await refreshedWorldPanel.getByText('虚构城', { exact: true }).first().waitFor();
    await refreshedWorldPanel.getByRole('button', { name: '原位置已有条目' }).waitFor();
    await page.locator('.inspector').screenshot({ path: path.join(fixture, 'world-card-trash.png') });
    assert.deepEqual(JSON.parse(await fs.readFile(worldFile, 'utf8')), beforeDelete);
    const cardBackups = await fs.readdir(path.join(folder, '小说资料', '世界设定卡回收站'));
    assert.equal(cardBackups.length, 1, '恢复后卡片备份仍保留');
    await page.getByTestId('inspector-world-cards').click();
    await page.getByRole('dialog', { name: '世界书' }).getByTestId('world-view-book').click();
    await page.getByTestId('world-card-browser').getByRole('heading', { name: '虚构城' }).waitFor();
    await page.getByRole('dialog', { name: '世界书' }).locator('footer').getByRole('button', { name: '关闭' }).click();
    await page.locator('.chapter-list').getByRole('button', { name: '第一章.txt' }).click();
    await page.locator('.tiptap').fill('尚未保存的本机草稿。');
    await page.getByRole('button', { name: '角色库', exact: true }).click();
    await page.getByTestId('setting-extract-open').click();
    assert.equal(await page.getByTestId('setting-book-prepare').isDisabled(), true, '有未保存正文时不得读取旧磁盘作为全文');
    assert.equal(await fs.readFile(chapter, 'utf8'), source);
    await page.getByRole('dialog', { name: '从文字设定提取' }).getByRole('button', { name: '关闭' }).click();
    await page.getByRole('button', { name: '写作空间', exact: true }).click();
    await app.evaluate(({dialog}, selected) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [selected] }); }, other.root);
    await page.getByRole('button', { name: '＋ 打开小说文件夹' }).click();
    await page.getByText('已打开「虚构另一本」', { exact: false }).waitFor();
    await page.getByRole('button', { name: '世界观', exact: true }).click();
    await page.getByRole('region', { name: '本书世界设定卡' }).getByText('还没有世界设定卡片，可从下方入口创建或整理。').waitFor();
    assert.equal(await page.getByRole('region', { name: '本书世界设定卡' }).getByText('虚构城', { exact: true }).count(), 0);
    await page.getByRole('button', { name: '人物', exact: true }).click();
    await page.getByRole('region', { name: '本书人物卡' }).getByText('还没有人物卡片，可从下方入口创建或整理。').waitFor();
    assert.equal(await page.getByRole('region', { name: '本书人物卡' }).getByText('虚构人物', { exact: true }).count(), 0);
    console.log('Whole-book settings desktop passed: preview, multi-request mock model, editable review, confirmed isolated records and unchanged source.');
  } finally { await app.evaluate(({app}) => app.exit(0)).catch(() => {}); server.closeAllConnections(); await new Promise<void>(resolve => server.close(() => resolve())); }
}
main().catch(error => { console.error(error); process.exitCode = 1; });
