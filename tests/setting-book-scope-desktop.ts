import { _electron as electron } from 'playwright';
import { createRequire } from 'node:module';
import { createServer } from 'node:http';
import { once } from 'node:events';
import * as fs from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';

async function main() {
  const sent: string[] = [];
  const server = createServer(async (request, response) => {
    let raw = ''; for await (const part of request) raw += part;
    sent.push(String(JSON.parse(raw).messages[1].content));
    const content = sent.length === 1 ? JSON.stringify({ world: [] }) : JSON.stringify({ characters: [{ name: '虚构人物', personality: '勇敢' }], world: [{ title: '未选类型的地点', content: '不会加入人物候选' }] });
    if (sent.length === 2) await new Promise(resolve => setTimeout(resolve, 400));
    response.writeHead(200, { 'Content-Type': 'text/event-stream' });
    response.end(`data: ${JSON.stringify({ choices: [{ index: 0, delta: { content }, finish_reason: 'stop' }] })}\n\ndata: [DONE]\n\n`);
  });
  server.listen(0, '127.0.0.1'); await once(server, 'listening');
  const fixture = await fs.mkdtemp(path.resolve('.artifacts/setting-scope-'));
  const folder = path.join(fixture, '虚构范围书'); await fs.mkdir(folder);
  const values = ['第一章未选择标记。'.repeat(30), '第二章选中标记。'.repeat(30), '第三章未选择标记。'.repeat(30)];
  for (const [index, content] of values.entries()) await fs.writeFile(path.join(folder, `0${index + 1}.txt`), content);
  const args = process.argv.slice(2); assert.ok(args.length === 0 || (args.length === 2 && args[0] === '--exe' && path.isAbsolute(args[1]!)));
  const env: Record<string, string> = Object.fromEntries(Object.entries(process.env).filter((entry): entry is [string, string] => typeof entry[1] === 'string'));
  env.NOVEL_WRITER_TEST_DATA = path.join(fixture, 'profile'); delete env.ELECTRON_RUN_AS_NODE;
  const app = await electron.launch({ executablePath: args.length ? args[1]! : createRequire(import.meta.url)('electron'), args: args.length ? [] : [path.resolve('out/main/index.js')], env });
  try {
    if (args.length) { const info = await app.evaluate(({app}) => ({ packaged: app.isPackaged, version: app.getVersion() })); assert.equal(info.packaged, true); assert.equal(info.version, JSON.parse(await fs.readFile('package.json', 'utf8')).version); }
    const page = await app.firstWindow(); page.setDefaultTimeout(30000); await page.setViewportSize({ width: 1000, height: 720 }); const dialogs: string[] = []; page.on('dialog', dialog => { dialogs.push(dialog.message()); void dialog.accept(); });
    await app.evaluate(({dialog}, selected) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [selected] }); }, folder);
    await page.getByRole('button', { name: '＋ 打开小说文件夹' }).click(); await page.getByText('已打开「虚构范围书」', { exact: false }).waitFor();
    const id = (await page.evaluate(() => window.writer.listProjects()))[0]!.id;
    await page.getByRole('button', { name: '模型设置', exact: true }).click();
    await page.getByLabel('连接名称', { exact: true }).fill('本机范围测试');
    await page.getByLabel('API 基础地址', { exact: true }).fill(`http://127.0.0.1:${(server.address() as {port:number}).port}/v1`);
    await page.getByLabel('模型名称', { exact: true }).fill('mock-scope');
    await page.getByRole('button', { name: '保存模型连接', exact: true }).click(); await page.getByText('模型连接已保存', { exact: true }).waitFor();
    await page.getByRole('button', { name: '角色库', exact: true }).click(); await page.getByTestId('setting-extract-open').click();
    const modal = page.getByTestId('setting-extract');
    await modal.getByLabel('整理目标').selectOption('character');
    assert.equal(await modal.getByLabel('失败分段自动重试一次').isChecked(), false, '额外请求必须由作者主动开启');
    await modal.getByLabel('失败分段自动重试一次').check();
    await modal.getByLabel('整理章节范围').selectOption('selected');
    await modal.getByLabel('选择章节 03.txt').waitFor();
    await modal.getByLabel('起始章节序号').fill('2'); await modal.getByLabel('结束章节序号').fill('3');
    await modal.getByRole('button', { name: '选择这一段' }).click();
    assert.equal(await modal.getByLabel('选择章节 01.txt').isChecked(), false);
    assert.equal(await modal.getByLabel('选择章节 02.txt').isChecked(), true);
    assert.equal(await modal.getByLabel('选择章节 03.txt').isChecked(), true);
    await modal.getByLabel('选择章节 03.txt').uncheck();
    await modal.getByText('已选择 1 / 3 章；按本书章节顺序发送。').waitFor();
    assert.equal(await modal.evaluate(element => element.scrollWidth > element.clientWidth), false);
    const aligned = await modal.getByLabel('选择章节 02.txt').evaluate(element => { const label = element.closest('label')!; const box = element.getBoundingClientRect(); const text = label.querySelector('span')!.getBoundingClientRect(); return Math.abs(box.top - text.top) < 8; });
    assert.equal(aligned, true, '章节复选框应与文字对齐');
    await modal.screenshot({ path: path.join(fixture, 'scope.png') });
    await modal.getByTestId('setting-book-prepare').click();
    const preview = modal.getByTestId('setting-book-preview'); await preview.getByText(/已读取 1 章（本书共 3 章）/u).waitFor();
    await preview.getByText(/启用重试后最多额外请求 1 次/u).waitFor();
    await preview.getByText('查看读取的章节').click(); assert.match(await preview.innerText(), /02\.txt/u); assert.doesNotMatch(await preview.innerText(), /01\.txt|03\.txt/u);
    await modal.getByLabel('选择章节 01.txt').check();
    assert.equal(await preview.count(), 0, '改变范围后不能沿用旧的发送预览');
    await modal.getByLabel('选择章节 01.txt').uncheck();
    await modal.getByTestId('setting-book-prepare').click(); await preview.getByText(/已读取 1 章/u).waitFor();
    await fs.writeFile(path.join(folder, '01.txt'), '未选章节的外部修改。'.repeat(30));
    await modal.getByTestId('setting-book-model').click();
    await modal.getByTestId('setting-book-progress').getByText(/第 1 段失败，正在重试/u).waitFor();
    await modal.getByLabel('选择 虚构人物').waitFor();
    assert.equal(await modal.getByText('未选类型的地点', { exact: false }).count(), 0, '未选择的类别不能进入候选');
    assert.equal(sent.length, 2); assert.equal(sent[0], sent[1], '只重发失败段');
    assert.ok(dialogs.some(message => /最多额外请求 1 次/u.test(message)), '确认时必须说明可能的额外请求');
    await modal.getByText('候选来源章节（1 章）').click();
    const provenance = modal.locator('details').filter({ hasText: '候选来源章节（1 章）' });
    assert.match(await provenance.innerText(), /02\.txt/u); assert.doesNotMatch(await provenance.innerText(), /01\.txt|03\.txt/u);
    assert.match(sent.join(''), /第二章选中标记/u); assert.doesNotMatch(sent.join(''), /第一章未选择标记|第三章未选择标记|未选章节的外部修改/u);
    assert.equal((await page.evaluate(projectId => window.writer.readCharacters(projectId), id)).value.cards.length, 0);
    await modal.getByLabel('选择章节 02.txt').uncheck(); await modal.getByLabel('选择章节 03.txt').check();
    await modal.getByLabel('选择 虚构人物').waitFor();
    await modal.getByTestId('setting-book-prepare').click(); await preview.getByText(/已读取 1 章/u).waitFor();
    assert.equal(await modal.getByLabel('选择 虚构人物').count(), 0, '确认重新读取后清除旧候选');
    await fs.writeFile(path.join(folder, '03.txt'), '选中章节的外部修改。'.repeat(30));
    const beforeCalls = sent.length; await modal.getByTestId('setting-book-model').click();
    await modal.getByRole('alert').getByText(/正文已变化/u).waitFor();
    assert.equal(sent.length, beforeCalls, '选中章节变动时不能发送过期正文');
    assert.equal(await fs.readFile(path.join(folder, '02.txt'), 'utf8'), values[1]);
    console.log('Book scope desktop passed: range and individual choice, explicit source list, isolated model input and selected-source conflict.');
  } finally { await app.evaluate(({app}) => app.exit(0)).catch(() => {}); server.closeAllConnections(); await new Promise<void>(resolve => server.close(() => resolve())); }
}
main().catch(error => { console.error(error); process.exitCode = 1; });
