import { _electron as electron } from 'playwright';
import { createServer } from 'node:http';
import { once } from 'node:events';
import { createRequire } from 'node:module';
import * as fs from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
import mammoth from 'mammoth';

async function main() {
  const calls: any[] = [];
  const server = createServer(async (req, res) => {
    let raw = ''; for await (const part of req) raw += part;
    const body = JSON.parse(raw); calls.push(body);
    res.writeHead(200, { 'Content-Type': 'text/event-stream' });
    const text = body.messages[0].content.includes('章节摘要助手') ? '林夏坐在窗边，天气下雨。' : body.messages[0].content.includes('只输出 JSON') ? JSON.stringify({ summary: '发现一个可定位错字，其余建议需核对', issues: [
      { category: '错别字', quote: '雨生', replacement: '雨声', reason: '此处描述雨的声音', evidence: '' },
      { category: '角色', quote: '林夏听见雨生。', replacement: '林夏冲出房间。', reason: '行为建议', evidence: '不存在的角色规则' }
    ] }) : body.messages[0].content.includes('独立审稿人') ? '审稿完成：未发现错别字。未提供大纲，未检查大纲一致性。' : body.messages[1]?.content.includes('测试逐项修改') ? '林夏听见雨生。\n她收起了信纸。' : '林夏听见雨声。\n她收起了信纸。';
    res.write(`data: ${JSON.stringify({ choices: [{ index: 0, delta: { reasoning_content: '不应出现在正文' }, finish_reason: null }] })}\n\n`);
    res.write(`data: ${JSON.stringify({ choices: [{ index: 0, delta: { content: text }, finish_reason: null }] })}\n\n`);
    setTimeout(() => res.end(`data: ${JSON.stringify({ choices: [{ index: 0, delta: {}, finish_reason: 'stop' }] })}\n\ndata: [DONE]\n\n`), 500);
  });
  server.listen(0, '127.0.0.1'); await once(server, 'listening');
  const port = (server.address() as { port: number }).port;
  const fixture = path.resolve('.artifacts', `ai-desktop-${Date.now()}`), folder = path.join(fixture, 'AI测试小说');
  await fs.mkdir(folder, { recursive: true });
  const require = createRequire(import.meta.url);
  const app = await electron.launch({ executablePath: require('electron'), args: [path.resolve('out/main/index.js')], env: { ...process.env, NOVEL_WRITER_TEST_DATA: path.join(fixture, 'app-data') } });
  const page = await app.firstWindow(); page.setDefaultTimeout(15000); const errors: string[] = [];
  page.on('pageerror', e => errors.push(e.message));
  try {
    await app.evaluate(({ dialog, clipboard }, selected) => {
      dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [selected] });
      clipboard.writeText = async text => { (globalThis as any).__copy = text; };
    }, folder);
    await page.getByRole('button', { name: '＋ 打开小说文件夹' }).click();
    await page.getByRole('button', { name: '＋ 新建 DOCX 章节' }).click();
    await page.locator('.tiptap').fill('林夏坐在窗边。');
    await page.getByRole('button', { name: '保存 DOCX', exact: true }).click();
    await page.getByText('DOCX 已保存到所选文件夹', { exact: true }).waitFor();
    const originalName = (await fs.readdir(folder)).find(name => name.endsWith('.docx'))!;
    const original = await fs.readFile(path.join(folder, originalName));
    await page.getByLabel('人物笔记').fill('林夏：说话温柔，学生。');
    await page.getByRole('button', { name: '保存本书资料' }).click();
    await page.getByText('本书资料已保存', { exact: true }).waitFor();
    await page.getByRole('button', { name: '模型设置', exact: true }).click();
    await page.getByLabel('快捷配置').selectOption({ label: 'DeepSeek' });
    await page.getByLabel('深度思考').selectOption('disabled');
    assert.equal(await page.getByLabel('参数适配').inputValue(), 'deepseek');
    await page.getByLabel('API 基础地址', { exact: true }).fill(`http://127.0.0.1:${port}/v1`);
    await page.getByLabel('连接名称', { exact: true }).fill('写作模型 A');
    await page.getByLabel('模型名称', { exact: true }).fill('mock-writer');
    await page.getByLabel('API 密钥', { exact: true }).fill('test-only-key');
    await page.getByRole('button', { name: '保存模型连接', exact: true }).click();
    await page.getByText('模型连接已保存', { exact: true }).waitFor();
    assert.equal(await page.getByLabel('API 密钥', { exact: true }).inputValue(), '');
    await page.getByRole('button', { name: '测试连接（少量 token）' }).click();
    await page.getByText('连接可用；已收到正文', { exact: false }).waitFor();
    await page.getByRole('button', { name: '＋ 新增模型连接' }).click();
    await page.getByLabel('快捷配置').selectOption({ label: '通义千问 · 百炼北京' });
    await page.getByLabel('深度思考').selectOption('disabled');
    await page.getByLabel('API 基础地址', { exact: true }).fill(`http://127.0.0.1:${port}/v1`);
    await page.getByLabel('连接名称', { exact: true }).fill('审稿模型 B');
    await page.getByLabel('模型名称', { exact: true }).fill('mock-reviewer');
    await page.getByRole('button', { name: '保存模型连接', exact: true }).click();
    await page.getByText('模型连接已保存', { exact: true }).waitFor();
    assert.ok(!(await fs.readFile(path.join(fixture, 'app-data', 'ai-connections.json'), 'utf8')).includes('test-only-key'));
    await page.getByRole('button', { name: '写作空间', exact: true }).click();
    await page.getByRole('button', { name: 'AI', exact: true }).click();
    await page.getByRole('button', { name: '打开 AI 写作与审稿' }).click();
    await page.getByLabel('写作模型', { exact: true }).selectOption({ label: '写作模型 A · mock-writer' });
    await page.getByLabel('审稿模型', { exact: true }).selectOption({ label: '审稿模型 B · mock-reviewer' });
    await page.getByRole('button', { name: '生成正文候选', exact: true }).click();
    await page.getByRole('heading', { name: '正文候选 · 已完成' }).waitFor();
    assert.equal(await page.getByLabel('AI 输出').textContent(), '林夏听见雨声。\n她收起了信纸。');
    await page.getByRole('button', { name: '复制结果' }).click();
    await page.getByText('AI 结果已复制', { exact: true }).waitFor();
    assert.equal(await app.evaluate(() => (globalThis as any).__copy), '　　林夏听见雨声。\n\n　　她收起了信纸。');
    await page.getByRole('button', { name: '候选另存 DOCX' }).click();
    await page.getByText('原正文保留', { exact: false }).waitFor();
    const candidates = (await fs.readdir(folder)).filter(name => name.endsWith('.docx') && name !== originalName);
    assert.equal(candidates.length, 1); assert.deepEqual(await fs.readFile(path.join(folder, originalName)), original);
    const plain = (await mammoth.extractRawText({ path: path.join(folder, candidates[0]) })).value;
    assert.match(plain, /　　林夏听见雨声。/);
    await page.getByRole('button', { name: '用审稿模型检查此候选' }).click();
    await page.getByRole('heading', { name: '审稿报告 · 已完成' }).waitFor();
    assert.match(await page.getByLabel('AI 输出').textContent() ?? '', /大纲/);
    assert.equal(calls.at(-1).model, 'mock-reviewer'); assert.equal(calls.at(-1).enable_thinking, false);
    assert.match(calls.at(-1).messages[1].content, /林夏听见雨声/);
    assert.deepEqual(calls.find(c => c.model === 'mock-writer').thinking, { type: 'disabled' });
    await page.getByLabel('生成后自动送审').check(); await page.getByLabel('写作要求').fill('测试逐项修改，生成新的正文候选。');
    await page.getByRole('button', { name: '生成正文候选', exact: true }).click();
    await page.getByText('自动送审：已完成', { exact: false }).waitFor();
    await page.getByRole('button', { name: '查看自动审稿报告', exact: true }).click();
    await page.getByRole('heading', { name: '逐项核对与采纳', exact: true }).waitFor();
    assert.equal(calls.at(-1).model, 'mock-reviewer');
    assert.equal(await page.getByLabel('采纳建议 issue-2').isDisabled(), true);
    await page.getByLabel('采纳建议 issue-1').check();
    await page.getByText('预览选中修改后的全文', { exact: true }).click();
    assert.equal(await page.getByLabel('审稿修订预览').textContent(), '林夏听见雨声。\n她收起了信纸。');
    await page.getByRole('button', { name: '采纳选中建议并另存 DOCX', exact: true }).click();
    await page.getByText('已另存修订稿', { exact: false }).waitFor();
    assert.deepEqual(await fs.readFile(path.join(folder, originalName)), original);
    const revisions = (await fs.readdir(folder)).filter(name => name.endsWith('.docx') && name !== originalName && !candidates.includes(name));
    assert.equal(revisions.length, 1); assert.match((await mammoth.extractRawText({ path: path.join(folder, revisions[0]) })).value, /　　林夏听见雨声。/);
    await page.evaluate(() => new Promise<void>(resolve => requestAnimationFrame(() => requestAnimationFrame(() => resolve()))));
    const png = await app.evaluate(async ({ BrowserWindow }) => (await BrowserWindow.getAllWindows()[0].webContents.capturePage(undefined, { stayHidden: true, stayAwake: true })).toPNG().toString('base64'));
    await fs.writeFile(path.resolve('.artifacts/ai-writer.png'), Buffer.from(png, 'base64'));
    await page.getByRole('button', { name: '配置模型连接' }).click();
    await page.getByRole('heading', { name: '模型设置', exact: true }).waitFor();
    await page.evaluate(() => new Promise<void>(resolve => requestAnimationFrame(() => requestAnimationFrame(() => resolve()))));
    const settingsPng = await app.evaluate(async ({ BrowserWindow }) => (await BrowserWindow.getAllWindows()[0].webContents.capturePage(undefined, { stayHidden: true, stayAwake: true })).toPNG().toString('base64'));
    await fs.writeFile(path.resolve('.artifacts/ai-settings.png'), Buffer.from(settingsPng, 'base64'));
    await page.getByRole('button', { name: '写作空间', exact: true }).click(); await page.getByRole('button', { name: '记忆', exact: true }).click();
    await page.getByRole('button', { name: '打开章节摘要与故事记忆', exact: true }).click();
    await page.getByLabel('摘要模型').selectOption({ label: '审稿模型 B · mock-reviewer' }); await page.getByRole('button', { name: '生成本章摘要', exact: true }).click();
    await page.getByRole('button', { name: '放入摘要确认稿', exact: true }).click(); await page.getByLabel('摘要确认稿').fill('林夏坐在窗边。');
    assert.equal(calls.at(-1).model, 'mock-reviewer');
    const projectId = (await page.evaluate(() => window.writer.listProjects()))[0].id;
    assert.equal((await page.evaluate(id => window.writer.readMemories(id), projectId)).value.entries.length, 0);
    await page.getByRole('button', { name: '确认保存并启用摘要', exact: true }).click(); await page.getByText('已确认保存并启用章节摘要', { exact: true }).waitFor();
    await page.getByRole('button', { name: '标记为重要摘要', exact: true }).click(); await page.getByRole('button', { name: '取消重要标记', exact: true }).waitFor();
    await page.getByRole('button', { name: '写作空间', exact: true }).click(); await page.getByRole('button', { name: 'AI', exact: true }).click(); await page.getByRole('button', { name: '打开 AI 写作与审稿', exact: true }).click();
    await page.getByLabel('生成后自动送审').uncheck(); await page.getByRole('button', { name: '生成正文候选', exact: true }).click();
    await page.getByRole('heading', { name: '正文候选 · 已完成', exact: true }).waitFor(); assert.match(calls.at(-1).messages[0].content, /作者确认的故事记忆[\s\S]*林夏坐在窗边/);
    await page.getByRole('button', { name: '写作空间', exact: true }).click(); await page.locator('.tiptap').fill('测试原文发生了变化。'); await page.getByRole('button', { name: '保存 DOCX', exact: true }).click(); await page.getByText('DOCX 已保存到所选文件夹', { exact: true }).waitFor();
    await page.getByRole('button', { name: '记忆', exact: true }).click(); await page.getByRole('button', { name: '打开章节摘要与故事记忆', exact: true }).click(); await page.getByRole('button', { name: '刷新摘要来源与保存基准', exact: true }).click(); await page.getByText('原文已变化或不可读：该摘要不会发送', { exact: false }).waitFor();
    await page.locator('.ai-page').filter({ visible: true }).evaluate(el => { el.scrollTop = 0; });
    await page.evaluate(() => new Promise<void>(resolve => requestAnimationFrame(() => requestAnimationFrame(() => resolve()))));
    const memoryPng = await app.evaluate(async ({ BrowserWindow }) => (await BrowserWindow.getAllWindows()[0].webContents.capturePage(undefined, { stayHidden: true, stayAwake: true })).toPNG().toString('base64')); await fs.writeFile(path.resolve('.artifacts/memories.png'), Buffer.from(memoryPng, 'base64'));
    assert.deepEqual(errors, []);
    console.log('AI desktop passed: encrypted models, automatic separate-model review, anchored edits, revision DOCX, confirmed independent-model summaries, importance, context injection and stale-source UI.');
  } finally { await app.evaluate(({ app: instance }) => instance.exit(0)); server.closeAllConnections(); await new Promise<void>(resolve => server.close(() => resolve())); }
}
main().catch(error => { console.error(error); process.exitCode = 1; });
