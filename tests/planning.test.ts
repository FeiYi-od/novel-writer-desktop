import { planningHeadings, validateOutline } from '../src/core/planning';
const outline = planningHeadings.outline.map(h => `## ${h}\n\n月光列车与失落的车站。`).join('\n\n');
async function fixture() {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'novel-planning-')); const data = path.join(root, 'local'), materials = path.join(root, 'materials');
  const workspace = new Workspace(data, materials); await workspace.initialize();
  await fs.mkdir(path.join(root, 'A')); await fs.mkdir(path.join(root, 'B'));
  const a = await workspace.attach(path.join(root, 'A')), b = await workspace.attach(path.join(root, 'B'));
  const planning = new PlanningStore(id => workspace.getProject(id), materials);
  return { root, data, materials, workspace, a, b, planning };
}
test('创作筹备 MD：按书提示词、草稿与正式大纲隔离，确认/冲突/历史与未来版本保护', async t => {
  const f = await fixture(); t.after(() => fs.rm(f.root, { recursive: true, force: true }));
  let current = await f.planning.read(f.a.id);
  current.value.prompts.outline = '请写学园悬疑'; current.value.drafts.outline = outline;
  current = await f.planning.save(f.a.id, current.value, current.hash);
  assert.equal(current.value.outline, ''); assert.equal((await f.planning.read(f.b.id)).value.drafts.outline, '');
  await assert.rejects(f.planning.save(f.b.id, current.value, ''), /另一部/);
  await f.planning.acceptOutline(f.a.id, current.hash);
  assert.equal((await f.planning.read(f.a.id)).value.outline, outline);
  await assert.rejects(f.planning.save(f.a.id, current.value, current.hash), /已更新/);
  const file = path.join(f.materials, f.a.id, '创作筹备.md'); const raw = await fs.readFile(file, 'utf8');
  await fs.writeFile(file, raw.replace('请写学园悬疑', '外部修改的提示词'));
  assert.equal((await f.planning.read(f.a.id)).value.prompts.outline, '外部修改的提示词');
  assert.ok((await fs.readdir(path.join(f.materials, f.a.id, 'history'))).length);
  await fs.writeFile(file, raw.replace('"schemaVersion":1', '"schemaVersion":99'));
  await assert.rejects(f.planning.read(f.a.id), /版本/);
  assert.throws(() => validateOutline('## 故事定位\n不完整的大纲'), /标题/);
});
test('筹备实际 HTTP：冻结本书构想，草稿不注入，确认大纲进入审稿，旧设定结果拒绝采用', async t => {
  const f = await fixture(); const calls: any[] = [];
  const server = createServer(async (req, res) => { let raw = ''; for await (const part of req) raw += part; calls.push(JSON.parse(raw)); res.writeHead(200, { 'Content-Type': 'text/event-stream' }); res.end(`data: ${JSON.stringify({ choices: [{ index: 0, delta: { content: outline }, finish_reason: 'stop' }] })}\n\ndata: [DONE]\n\n`); });
  await listenLocalHttp(server);
  t.after(async () => { server.closeAllConnections(); await new Promise<void>(resolve => server.close(() => resolve())); await fs.rm(f.root, { recursive: true, force: true }); });
  const connections = new AIConnections(f.data, { encrypt: text => Buffer.from(text), decrypt: bytes => bytes.toString() });
  const settings = await connections.save({ name: 'mock', model: 'mock', baseUrl: `http://127.0.0.1:${(server.address() as { port: number }).port}/v1`, adapter: 'generic', thinking: 'default', contextWindow: 32768, maxOutputTokens: 2048, tokenParameter: 'max_tokens', timeoutSeconds: 30 }, '');
  const service = new AIService(f.data, connections, f.workspace, new LibraryStore(id => f.workspace.getProject(id), f.materials), new CharacterStore(id => f.workspace.getProject(id), f.materials), f.planning);
  const wait = async (taskId: string) => { for (let i = 0; i < 150; i++) { const task = (await service.list(f.a.id)).find(t => t.id === taskId); if (task && task.status !== 'running') return task; await new Promise(resolve => setTimeout(resolve, 20)); } throw new Error('等待筹备任务超时'); };
  let current = await f.planning.read(f.a.id); current.value.briefs.outline = '月光列车寻找失落的车站'; current.value.drafts.world = '不应注入的废稿';
  current = await f.planning.save(f.a.id, current.value, current.hash);
  const bn = await f.workspace.readNotes(f.b.id); await f.workspace.saveNotes(f.b.id, { ...bn.value, world: '乙书不能出现的秘密' }, bn.hash);
  const task = await service.startPlanning({ projectId: f.a.id, connectionId: settings.connections[0].id, kind: 'outline', expectedHash: current.hash });
  const result = await wait(task.id); assert.equal(result.status, 'complete'); assert.equal(result.mode, 'plan-outline');
  assert.match(calls[0].messages[1].content, /月光列车/); assert.doesNotMatch(JSON.stringify(calls[0]), /不应注入的废稿|乙书不能出现/);
  assert.equal((await f.planning.read(f.a.id)).value.outline, ''); assert.equal((await service.list(f.b.id)).length, 0);
  await assert.rejects(service.assertPlanningCandidate(f.b.id, 'outline', task.id), /未找到/);
  await service.assertPlanningCandidate(f.a.id, 'outline', task.id);
  current.value.drafts.outline = result.text; current.value.originTasks.outline = task.id; current = await f.planning.save(f.a.id, current.value, current.hash);
  await f.planning.acceptOutline(f.a.id, current.hash);
  const doc = await f.workspace.createChapter(f.a.id);
  const review = await service.start({ projectId: f.a.id, connectionId: settings.connections[0].id, mode: 'review', chapterPath: doc.path, sourceHash: doc.hash, instruction: '检查大纲' }); await wait(review.id);
  assert.match(calls.at(-1).messages[0].content, /已确认故事大纲：[\s\S]*月光列车/);
  await assert.rejects(service.assertPlanningCandidate(f.a.id, 'outline', task.id), /设定已变化/);
  await assert.rejects(service.startPlanning({ projectId: f.a.id, connectionId: settings.connections[0].id, kind: 'world', expectedHash: 'stale' }), /已变化/);
});
